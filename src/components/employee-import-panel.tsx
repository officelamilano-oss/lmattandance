async function sendFile<T>(url: string, file: File) {
  const body = new FormData();
  body.set("file", file);
  const response = await fetch(url, { method: "POST", body });
  return readResponse<T>(response);
}

async function sendImport<T>(
  url: string,
  file: File,
  fieldsToSend: Record<string, string>,
) {
  const body = new FormData();
  body.set("file", file);
  for (const [key, value] of Object.entries(fieldsToSend))
    body.set(key, value);
  const response = await fetch(url, { method: "PUT", body });
  return readResponse<T>(response);
}

function csvCell(value: string) {
  return `"${value.replace(/"/g, '""')}"`;
}

/**
 * Builds a clean CSV from the edited table so the existing import route
 * (which reads a file + column mapping) receives the user's edits.
 */
function buildEditedCsv(rows: EditableRow[]) {
  const header = fields.map((field) => csvCell(field.label)).join(",");
  const lines = rows.map((row) =>
    fields.map((field) => csvCell(String(row[field.key] ?? "").trim())).join(","),
  );
  return [header, ...lines].join("\r\n");
}

async function readResponse<T>(response: Response) {
  const payload = await response.json().catch(() => ({}));
  if (!response.ok) {
    const details = Array.isArray(payload.details)
      ? payload.details
          .map((detail: { message?: string }) => detail.message)
          .filter(Boolean)
          .join(" ")
      : "";
    throw new Error(
      details
        ? `${payload.error ?? "Request failed."} ${details}`
        : (payload.error ?? "Request failed."),
    );
  }
  return payload as T;
}

function normalizeHeader(value: string) {
  return String(value)
    .toLowerCase()
    .replace(/\(.*?\)/g, " ") // "(optional)", "(required)"
    .replace(/%/g, " percent ") // "Employee PF %" -> "employee pf percent"
    .replace(/[*:]/g, " ") // "Full name *"
    .replace(/[_-]+/g, " ")
    .replace(/\s+/g, " ")
    .trim();
}

function detectMapping(preview: Preview) {
  const result = {} as Record<ImportField, string>;
  const usedColumns = new Set<number>();
  const labels = preview.columns.map((column) => ({
    index: column.index,
    text: normalizeHeader(column.label),
  }));

  // Pass 1: header equals one of the aliases (after cleaning * ( ) %).
  for (const field of fields) {
    const hit = labels.find(
      (label) => !usedColumns.has(label.index) && field.aliases.includes(label.text),
    );
    result[field.key] = hit ? String(hit.index) : "";
    if (hit) usedColumns.add(hit.index);
  }

  // Pass 2: header contains an alias as whole words, e.g. "Staff full name".
  for (const field of fields) {
    if (result[field.key] !== "") continue;
    const aliases = [...field.aliases].sort((a, b) => b.length - a.length);
    const hit = labels.find(
      (label) =>
        !usedColumns.has(label.index) &&
        aliases.some((alias) => ` ${label.text} `.includes(` ${alias} `)),
    );
    if (hit) {
      result[field.key] = String(hit.index);
      usedColumns.add(hit.index);
    }
  }
  return result;
}

function numericValue(value: string | number | boolean | null | undefined) {
  if (value === null || value === undefined || value === "") return undefined;
  const parsed = Number(String(value).replace(/[₹,\s]/g, ""));
  return Number.isFinite(parsed) ? parsed : undefined;
}

/** Converts dd-mm-yyyy, dd/mm/yyyy, Excel serial numbers or ISO strings to yyyy-mm-dd. */
function toIsoDate(value: string | number | boolean | null | undefined) {
  if (value === null || value === undefined || value === "") return "";
  const text = String(value).trim();

  const dmy = text.match(/^(\d{1,2})[-/.](\d{1,2})[-/.](\d{4})$/);
  if (dmy) return `${dmy[3]}-${dmy[2].padStart(2, "0")}-${dmy[1].padStart(2, "0")}`;

  const iso = text.match(/^(\d{4})-(\d{2})-(\d{2})/);
  if (iso) return `${iso[1]}-${iso[2]}-${iso[3]}`;

  const serial = Number(text);
  if (Number.isFinite(serial) && serial > 20000 && serial < 80000) {
    const date = new Date(Math.round((serial - 25569) * 86400 * 1000));
    return date.toISOString().slice(0, 10);
  }
  // Other formats such as "Mon Apr 01 2019" or "1 Apr 2019".
  if (/[a-z]/i.test(text)) {
    const parsed = new Date(text);
    if (!Number.isNaN(parsed.getTime())) {
      const month = String(parsed.getMonth() + 1).padStart(2, "0");
      const day = String(parsed.getDate()).padStart(2, "0");
      return `${parsed.getFullYear()}-${month}-${day}`;
    }
  }
  // Not a real date (e.g. text in the date column): leave the cell empty.
  return "";
}

function toYesNo(value: string | number | boolean | null | undefined) {
  if (value === null || value === undefined || String(value).trim() === "")
    return "No";
  return /^(yes|y|true|1)$/i.test(String(value).trim()) ? "Yes" : "No";
}

/** Reads one field of one sheet row, applying the default if the cell is blank. */
function readField(
  row: Preview["rows"][number],
  mapping: Record<ImportField, string>,
  key: ImportField,
) {
  const column = mapping[key];
  const raw = column === "" ? null : row.values[Number(column)];
  if (key === "dateOfJoining") return toIsoDate(raw);
  if (yesNoFields.includes(key)) return toYesNo(raw);
  const text = raw === null || raw === undefined ? "" : String(raw).trim();
  return text === "" ? (DEFAULTS[key] ?? "") : text;
}

function buildRows(preview: Preview, mapping: Record<ImportField, string>) {
  return preview.rows.map((row, index) => {
    const values = Object.fromEntries(
      fields.map((field) => [field.key, readField(row, mapping, field.key)]),
    ) as Record<ImportField, string>;
    return {
      ...values,
      sheetRow: index + 2,
      autoCode: values.employeeCode === "",
    } satisfies EditableRow;
  });
}

/** Outlet "Head office" -> "HEA". Matches the "HEA + 4 digits" format of Add employee. */
function codePrefix(outlet: DashboardOutlet) {
  const letters = String(outlet.name ?? outlet.code ?? "")
    .replace(/[^a-z0-9]/gi, "")
    .toUpperCase();
  return letters.slice(0, 3) || "EMP";
}

/**
 * Gives every row with an app-generated (or empty) code the next free number
 * for the outlet prefix. Codes typed by the user or read from the sheet stay.
 */
function assignCodes(
  rows: EditableRow[],
  outlet: DashboardOutlet | undefined,
  existingCodes: string[],
) {
  if (!outlet) return rows;
  const prefix = codePrefix(outlet);
  const pattern = new RegExp(`^${prefix}(\\d+)$`);
  const used = new Set<string>();
  let max = 0;
  const reserve = (code: string) => {
    const clean = code.trim().toUpperCase();
    if (!clean) return;
    used.add(clean);
    const match = clean.match(pattern);
    if (match) max = Math.max(max, Number(match[1]));
  };
  existingCodes.forEach(reserve);
  rows.forEach((row) => {
    if (!row.autoCode) reserve(row.employeeCode);
  });
  return rows.map((row) => {
    if (!row.autoCode && row.employeeCode.trim()) return row;
    let code = "";
    do {
      max += 1;
      code = `${prefix}${String(max).padStart(4, "0")}`;
    } while (used.has(code));
    used.add(code);
    return { ...row, employeeCode: code, autoCode: true };
  });
}

function rowProblems(row: EditableRow, rows: EditableRow[]) {
  const problems = new Set<ImportField>();
  for (const field of requiredFields)
    if (!row[field.key].trim()) problems.add(field.key);
  if (
    row.employeeCode.trim() &&
    rows.filter(
      (other) =>
        other.employeeCode.trim().toLowerCase() ===
        row.employeeCode.trim().toLowerCase(),
    ).length > 1
  )
    problems.add("employeeCode");
  if (numericValue(row.monthlyBaseSalary) === undefined)
    problems.add("monthlyBaseSalary");
  for (const key of numberFields) {
    if (
      key !== "monthlyBaseSalary" &&
      row[key].trim() &&
      numericValue(row[key]) === undefined
    )
      problems.add(key);
  }
  return problems;
}

function duplicateKey(row: EditableRow) {
  return [
    row.fullName.trim().toLowerCase(),
    row.dateOfJoining,
    row.designation.trim().toLowerCase(),
  ].join("|");
}

export function EmployeeImportPanel({
  outlets,
  selectedOutlet,
  onImported,
  existingEmployeeCodes = [],
}: {
  outlets: DashboardOutlet[];
  selectedOutlet: string;
  onImported: () => Promise<void>;
  /** Optional: codes already in the database, so generated codes never clash. */
  existingEmployeeCodes?: string[];
}) {
  const [file, setFile] = useState<File>();
  const [fileInputKey, setFileInputKey] = useState(0);
  const [preview, setPreview] = useState<Preview>();
  const [mapping, setMapping] = useState<Record<ImportField, string>>();
  const [editRows, setEditRows] = useState<EditableRow[]>([]);
  const [outletId, setOutletId] = useState(selectedOutlet);
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState("");
  const [success, setSuccess] = useState("");

  const activeOutletId = outletId || selectedOutlet;
  const activeOutlet = outlets.find((outlet) => outlet._id === activeOutletId);

  const problems = useMemo(
    () => editRows.map((row) => rowProblems(row, editRows)),
    [editRows],
  );
  const invalidCount = problems.filter((set) => set.size > 0).length;

  const duplicateRows = useMemo(() => {
    const seen = new Set<string>();
    const duplicates = new Set<number>();
    for (const row of editRows) {
      if (!row.fullName.trim()) continue;
      const key = duplicateKey(row);
      if (seen.has(key)) duplicates.add(row.sheetRow);
      else seen.add(key);
    }
    return duplicates;
  }, [editRows]);

  // Fields with no sheet column that matter for the data (code is auto-generated).
  const unmappedFields = mapping
    ? fields.filter(
        (field) =>
          mapping[field.key] === "" &&
          (field.required || field.key === "monthlyBaseSalary") &&
          field.key !== "employeeCode",
      )
    : [];

  const noDateCount = editRows.filter(
    (row) => !row.dateOfJoining || !row.fullName.trim(),
  ).length;

  async function upload(event: FormEvent<HTMLFormElement>) {
    event.preventDefault();
    if (!file) {
      setError("Choose a CSV or Excel .xlsx file first.");
      return;
    }
    setBusy(true);
    setError("");
    setSuccess("");
    try {
      const result = await sendFile<Preview>("/api/employees/import", file);
      const detected = detectMapping(result);
      setPreview(result);
      setMapping(detected);
      setEditRows(
        assignCodes(
          buildRows(result, detected),
          outlets.find((outlet) => outlet._id === activeOutletId),
          existingEmployeeCodes,
        ),
      );
    } catch (caught) {
      setError(
        caught instanceof Error ? caught.message : "Unable to read this sheet.",
      );
    } finally {
      setBusy(false);
    }
  }

  function changeOutlet(nextId: string) {
    setOutletId(nextId);
    setEditRows((current) =>
      assignCodes(
        current,
        outlets.find((outlet) => outlet._id === nextId),
        existingEmployeeCodes,
      ),
    );
  }

  function regenerateCodes() {
    setEditRows((current) =>
      assignCodes(
        current.map((row) => ({ ...row, autoCode: true })),
        activeOutlet,
        existingEmployeeCodes,
      ),
    );
  }

  function changeMapping(key: ImportField, value: string) {
    if (!mapping || !preview) return;
    const next = { ...mapping, [key]: value };
    setMapping(next);
    // Only the changed field is refreshed from the sheet; other edits stay.
    const refreshed = editRows.map((row) => {
      const source = preview.rows[row.sheetRow - 2];
      if (!source) return row;
      const fieldValue = readField(source, next, key);
      return key === "employeeCode"
        ? { ...row, employeeCode: fieldValue, autoCode: fieldValue === "" }
        : { ...row, [key]: fieldValue };
    });
    setEditRows(
      key === "employeeCode"
        ? assignCodes(refreshed, activeOutlet, existingEmployeeCodes)
        : refreshed,
    );
  }

  function updateCell(sheetRow: number, key: ImportField, value: string) {
    setEditRows((current) =>
      current.map((row) =>
        row.sheetRow === sheetRow
          ? {
              ...row,
              [key]: value,
              ...(key === "employeeCode"
                ? { autoCode: value.trim() === "" }
                : {}),
            }
          : row,
      ),
    );
  }

  function removeRow(sheetRow: number) {
    setEditRows((current) => current.filter((row) => row.sheetRow !== sheetRow));
  }

  function removeRowsWithoutDate() {
    setEditRows((current) =>
      current.filter((row) => row.dateOfJoining && row.fullName.trim()),
    );
  }

  function removeDuplicates() {
    setEditRows((current) => {
      const seen = new Set<string>();
      return current.filter((row) => {
        if (!row.fullName.trim()) return true;
        const key = duplicateKey(row);
        if (seen.has(key)) return false;
        seen.add(key);
        return true;
      });
    });
  }

  async function importSheet(event: FormEvent<HTMLFormElement>) {
    event.preventDefault();
    if (!editRows.length) {
      setError("There are no employee rows left to import.");
      return;
    }
    if (!activeOutletId) {
      setError("Choose an outlet for this import.");
      return;
    }
    if (invalidCount) {
      setError(
        `${invalidCount} row(s) have missing or invalid values. Fix the highlighted cells.`,
      );
      return;
    }
    if (
      !window.confirm(
        `Import ${editRows.length} employee rows into ${activeOutlet?.name ?? "the selected outlet"}?${
          duplicateRows.size
            ? ` ${duplicateRows.size} row(s) look like duplicates.`
            : ""
        } Matching employee codes will update existing workers.`,
      )
    )
      return;

    setBusy(true);
    setError("");
    setSuccess("");
    try {
      // The edited table is sent as a fresh CSV, one column per field, in the
      // same order as `fields`. The server route stays unchanged.
      const editedFile = new File([buildEditedCsv(editRows)], "edited-employees.csv", {
        type: "text/csv",
      });
      const fixedMapping = Object.fromEntries(
        fields.map((field, index) => [field.key, index]),
      );
      const result = await sendImport<{
        imported: number;
        added: number;
        updated: number;
      }>("/api/employees/import", editedFile, {
        outletId: activeOutletId,
        salaryMode: "sheet",
        mapping: JSON.stringify(fixedMapping),
        manualSalaries: JSON.stringify({}),
      });
      setSuccess(
        `Imported ${result.imported} workers: ${result.added} added, ${result.updated} updated.`,
      );
      setPreview(undefined);
      setMapping(undefined);
      setEditRows([]);
      setFile(undefined);
      setFileInputKey((current) => current + 1);
      await onImported();
    } catch (caught) {
      setError(
        caught instanceof Error ? caught.message : "Unable to import this sheet.",
      );
    } finally {
      setBusy(false);
    }
  }

  return (
    <details className="panel form-panel employee-import-panel">
      <summary>
        <FileSpreadsheet size={17} /> Import employee sheet
      </summary>
      {error && (
        <AutoDismissNotice
          key={`error:${error}`}
          message={error}
          variant="error"
        />
      )}
      {success && (
        <AutoDismissNotice
          key={`success:${success}`}
          message={success}
          variant="success"
        />
      )}
      <form className="form-grid" onSubmit={upload}>
        <label className="field">
          <span>Employee spreadsheet (CSV or .xlsx, up to 5 MB)</span>
          <input
            key={fileInputKey}
            type="file"
            accept=".csv,.xlsx,text/csv,application/vnd.openxmlformats-officedocument.spreadsheetml.sheet"
            onChange={(event) => {
              setFile(event.target.files?.[0]);
              setPreview(undefined);
              setMapping(undefined);
              setEditRows([]);
              setError("");
              setSuccess("");
            }}
            required
          />
        </label>
        <div className="form-actions">
          <button className="button button-secondary" disabled={busy || !file}>
            {busy ? (
              <LoaderCircle className="spin" size={16} />
            ) : (
              <Upload size={16} />
            )}
            Preview sheet
          </button>
        </div>
      </form>

      {preview && mapping && (
        <form className="form-grid import-mapping" onSubmit={importSheet}>
          <label className="field">
            <span>Outlet * (employee codes are generated from it)</span>
            <select
              value={activeOutletId}
              onChange={(event) => changeOutlet(event.target.value)}
              required
            >
              <option value="">Choose outlet</option>
              {outlets
                .filter((outlet) => outlet.active)
                .map((outlet) => (
                  <option key={outlet._id} value={outlet._id}>
                    {outlet.code} · {outlet.name}
                  </option>
                ))}
            </select>
          </label>

          {unmappedFields.length > 0 && (
            <p style={{ gridColumn: "1 / -1", color: "#b26a00" }}>
              These columns were not found in your sheet:{" "}
              {unmappedFields.map((field) => field.label).join(", ")}. If they
              are in the sheet under another name, choose them in Column
              mapping below.
            </p>
          )}

          <details
            style={{ gridColumn: "1 / -1" }}
            open={unmappedFields.length > 0}
          >
            <summary>Column mapping (auto-detected, change only if needed)</summary>
            <div className="form-grid" style={{ marginTop: 12 }}>
              {fields.map((field) => (
                <label className="field" key={field.key}>
                  <span>
                    {field.label}
                    {field.key === "employeeCode"
                      ? " (blank = auto-generate)"
                      : DEFAULTS[field.key] !== undefined
                        ? ` (blank = ${DEFAULTS[field.key]})`
                        : field.required
                          ? " *"
                          : " (optional)"}
                  </span>
                  <select
                    value={mapping[field.key]}
                    onChange={(event) =>
                      changeMapping(field.key, event.target.value)
                    }
                  >
                    <option value="">Not in sheet</option>
                    {preview.columns.map((column) => (
                      <option key={column.index} value={column.index}>
                        {column.label}
                      </option>
                    ))}
                  </select>
                </label>
              ))}
            </div>
          </details>

          <div className="import-preview-table" style={{ gridColumn: "1 / -1" }}>
            <strong>
              Edit before importing · {editRows.length} employee row(s)
            </strong>
            <p>
              Change any cell. Red cells are missing or invalid. Fields that are
              not in the sheet use defaults: Full-time, PF No, ESI No.
            </p>
            <div
              style={{
                display: "flex",
                flexWrap: "wrap",
                gap: 8,
                margin: "8px 0",
              }}
            >
              <button
                type="button"
                className="button button-secondary"
                onClick={regenerateCodes}
                disabled={!activeOutlet}
              >
                <RefreshCw size={15} /> Auto-generate codes
              </button>
              {noDateCount > 0 && (
                <button
                  type="button"
                  className="button button-secondary"
                  onClick={removeRowsWithoutDate}
                >
                  <Trash2 size={15} /> Remove {noDateCount} row(s) without name
                  or joining date
                </button>
              )}
              {duplicateRows.size > 0 && (
                <button
                  type="button"
                  className="button button-secondary"
                  onClick={removeDuplicates}
                >
                  <Trash2 size={15} /> Remove {duplicateRows.size} duplicate
                  row(s)
                </button>
              )}
            </div>
            {!activeOutlet && (
              <p>Select an outlet to fill employee codes automatically.</p>
            )}
            <div className="table-wrap" style={{ overflowX: "auto" }}>
              <table>
                <thead>
                  <tr>
                    <th>Row</th>
                    {fields.map((field) => (
                      <th key={field.key}>
                        {field.label}
                        {field.required ? " *" : ""}
                      </th>
                    ))}
                    <th />
                  </tr>
                </thead>
                <tbody>
                  {editRows.map((row, rowIndex) => (
                    <tr key={row.sheetRow}>
                      <td>
                        {row.sheetRow}
                        {duplicateRows.has(row.sheetRow) && (
                          <div style={{ color: "#b26a00", fontSize: 12 }}>
                            Duplicate
                          </div>
                        )}
                      </td>
                      {fields.map((field) => {
                        const invalid = problems[rowIndex]?.has(field.key);
                        const style = {
                          minWidth: field.width,
                          width: "100%",
                          ...(invalid
                            ? { borderColor: "#d64545", background: "#fdecec" }
                            : {}),
                        };
                        return (
                          <td key={field.key}>
                            {yesNoFields.includes(field.key) ? (
                              <select
                                className="cell-input"
                                style={style}
                                value={row[field.key]}
                                onChange={(event) =>
                                  updateCell(
                                    row.sheetRow,
                                    field.key,
                                    event.target.value,
                                  )
                                }
                              >
                                <option value="No">No</option>
                                <option value="Yes">Yes</option>
                              </select>
                            ) : field.key === "employmentType" ? (
                              <select
                                className="cell-input"
                                style={style}
                                value={row[field.key] || "Full-time"}
                                onChange={(event) =>
                                  updateCell(
                                    row.sheetRow,
                                    field.key,
                                    event.target.value,
                                  )
                                }
                              >
                                <option value="Full-time">Full-time</option>
                                <option value="Part-time">Part-time</option>
                                {row[field.key] &&
                                  !["Full-time", "Part-time"].includes(
                                    row[field.key],
                                  ) && (
                                    <option value={row[field.key]}>
                                      {row[field.key]}
                                    </option>
                                  )}
                              </select>
                            ) : (
                              <input
                                className="cell-input"
                                style={style}
                                type={
                                  field.key === "dateOfJoining"
                                    ? "date"
                                    : numberFields.includes(field.key)
                                      ? "number"
                                      : "text"
                                }
                                min={
                                  numberFields.includes(field.key)
                                    ? "0"
                                    : undefined
                                }
                                step={
                                  numberFields.includes(field.key)
                                    ? "0.01"
                                    : undefined
                                }
                                value={row[field.key]}
                                onChange={(event) =>
                                  updateCell(
                                    row.sheetRow,
                                    field.key,
                                    event.target.value,
                                  )
                                }
                              />
                            )}
                          </td>
                        );
                      })}
                      <td>
                        <button
                          type="button"
                          className="button button-secondary"
                          aria-label={`Remove row ${row.sheetRow}`}
                          onClick={() => removeRow(row.sheetRow)}
                        >
                          <Trash2 size={15} />
                        </button>
                      </td>
                    </tr>
                  ))}
                </tbody>
              </table>
            </div>
            {invalidCount > 0 && (
              <p>
                {invalidCount} row(s) still need attention before you can
                import.
              </p>
            )}
          </div>

          <div className="form-actions">
            <button
              className="button button-primary"
              disabled={busy || !editRows.length || !activeOutletId}
            >
              {busy ? (
                <LoaderCircle className="spin" size={16} />
              ) : (
                <Check size={16} />
              )}
              Import {editRows.length} rows
            </button>
          </div>
        </form>
      )}
    </details>
  );
}